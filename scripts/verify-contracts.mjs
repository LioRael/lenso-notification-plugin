if ("source" in receiptRequest.properties) {
  throw new Error("receipt Provider identity must not be accepted from payload");
}
const dispatchResponse = JSON.parse(
  await readFile(
    resolve(
      root,
      "crates/lenso-capability-email-dispatch/schemas/dispatch-response.schema.json",
    ),
    "utf8",
  ),
);
const acceptedBranch = dispatchResponse.then?.properties;
const temporaryCondition = dispatchResponse.else;
const temporaryBranch = temporaryCondition?.then?.properties;
const permanentCondition = temporaryCondition?.else;
const permanentBranch = permanentCondition?.then?.properties;
const unknownBranch = permanentCondition?.else?.properties;
if (
  dispatchResponse.if?.properties?.outcome?.const !== "accepted" ||
  temporaryCondition?.if?.properties?.outcome?.const !== "temporary_failure" ||
  permanentCondition?.if?.properties?.outcome?.const !== "permanent_failure" ||
  acceptedBranch?.failure?.const !== null ||
  temporaryBranch?.remote_receipt?.const !== null ||
  temporaryBranch?.failure?.type !== "object" ||
  temporaryBranch?.failure?.properties?.classification?.const !==
    "temporary_failure" ||
  permanentBranch?.remote_receipt?.const !== null ||
  permanentBranch?.failure?.type !== "object" ||
  permanentBranch?.failure?.properties?.classification?.const !==
    "permanent_failure" ||
  permanentBranch?.failure?.properties?.retry_after_ms?.const !== null ||
  unknownBranch?.remote_receipt?.const !== null ||
  unknownBranch?.failure?.type !== "object" ||
  unknownBranch?.failure?.properties?.classification?.const !==
    "delivery_unknown" ||
  unknownBranch?.failure?.properties?.retry_after_ms?.const !== null
) {
  throw new Error("email dispatch response cross-field schema drift");
}

const businessPath = resolve(
  root,
  "packages/notification-console/src/notification-business-api.v1.json",
);
const business = await readFile(businessPath);
const digest = `sha256:${createHash("sha256").update(business).digest("hex")}`;
const typescript = await readFile(
  resolve(root, "packages/notification-console/src/business-api.ts"),
  "utf8",
);
if (!typescript.includes(digest)) {
  throw new Error(`static Console adapter digest drift: expected ${digest}`);
}

console.log(
  `Verified ${contracts.length} Capability descriptors/projections and static Console adapter ${digest}`,
);
