function verifySchemaBounds(value, schemaPath = "$") {
  if (Array.isArray(value)) {
    value.forEach((child, index) =>
      verifySchemaBounds(child, `${schemaPath}[${index}]`),
    );
    return;
  }
  if (value === null || typeof value !== "object") {
    return;
  }
  if (
    value.format === "date-time" &&
    (value.minLength !== 1 || value.maxLength !== 64)
  ) {
    throw new Error(`${schemaPath} date-time must be bounded to 1..64 bytes`);
  }
  if (
    value.pattern !== undefined &&
    value.pattern !== "^sha256:[0-9a-f]{64}$"
  ) {
    throw new Error(`${schemaPath} has an unapproved or non-exact pattern`);
  }
  for (const [key, child] of Object.entries(value)) {
    verifySchemaBounds(child, `${schemaPath}.${key}`);
  }
}

for (const contract of contracts) {
  const directory = resolve(root, "crates", contract.directory);
  const descriptor = JSON.parse(
    await readFile(resolve(directory, "capability.json"), "utf8"),
  );
  if (descriptor.id !== contract.id || descriptor.version !== "1.0.0") {
    throw new Error(`${contract.id} identity drift`);
  }
  if (descriptor.portable !== true || descriptor.cross_lane_transfer !== true) {
    throw new Error(
      `${contract.id} must stay portable and cross-lane transferable`,
    );
  }
  if (
    JSON.stringify(descriptor.operations.map(({ name }) => name)) !==
    JSON.stringify(contract.operations)
  ) {
    throw new Error(`${contract.id} operation drift`);
  }
  const generated = await readFile(
    resolve(directory, "src", "generated.rs"),
    "utf8",
  );
  if (
    !generated.startsWith(
      "// @generated by lenso-contract-codegen; do not edit.",
    )
  ) {
    throw new Error(`${contract.id} Rust projection is not generated`);
  }
  if (
    !generated.includes(
      `pub const CAPABILITY_ID: &str = ${JSON.stringify(contract.id)}`,
    )
  ) {
    throw new Error(`${contract.id} Rust projection identity drift`);
  }
  for (const operation of descriptor.operations) {
    for (const schema of [
      operation.request_schema,
      operation.response_schema,
      operation.domain_error_schema,
    ]) {
      const schemaFile = resolve(directory, schema);
      await access(schemaFile);
      const parsedSchema = JSON.parse(await readFile(schemaFile, "utf8"));
      verifySchemaBounds(parsedSchema, `${contract.id}:${schema}`);
    }
  }
}

